#!/usr/bin/env python3
# Generates kernel/gfx/font8x16.cpp (1-bit 8x16 glyphs for ASCII 32..126)
# by rasterizing DejaVu Sans Mono. Used only by the panic screen / early boot.
from PIL import Image, ImageDraw, ImageFont
import sys
font = ImageFont.truetype(sys.argv[1], 13)
out = ["// Generated by tools/gen_font8x16.py from DejaVu Sans Mono. Do not edit.",
       '#include "gfx/font8x16.h"', "", "static const uint8_t kGlyphs[95][16] = {"]
for c in range(32, 127):
    im = Image.new("L", (8, 16), 0)
    d = ImageDraw.Draw(im)
    d.text((0, 0), chr(c), fill=255, font=font)
    rows = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)) > 100: b |= 0x80 >> x
        rows.append("0x%02x" % b)
    out.append("    {" + ",".join(rows) + "},  // %r" % chr(c))
out += ["};", "", "static const uint8_t kEmpty[16] = {0};", "",
        "const uint8_t* font8x16_glyph(uint8_t c) {",
        "    if (c < 32 || c > 126) return kEmpty;",
        "    return kGlyphs[c - 32];", "}", ""]
open(sys.argv[2], "w").write("\n".join(out))
